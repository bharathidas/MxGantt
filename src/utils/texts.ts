type Groups = typeof TEXT_GROUPS;
export type TextKey = { [G in keyof Groups]: keyof Groups[G] }[keyof Groups];
export type Texts = Record<TextKey, string>;

export const DEFAULT_TEXTS: Texts = Object.assign({}, ...Object.values(TEXT_GROUPS)) as Texts;

export function textPropertyKey(key: string): string {
    return `txt${key.charAt(0).toUpperCase()}${key.slice(1)}`;
}

/** Fills [name] placeholders. */
export function fill(template: string, values: Record<string, string | number>): string {
    return template.replace(/\[(\w+)\]/g, (match, name: string) => (name in values ? String(values[name]) : match));
}

/** Reads the configured texts off the widget props, falling back to the defaults. */
export function readTexts(props: object): Texts {
    const source = props as Record<string, { value?: string } | undefined>;
    const texts = { ...DEFAULT_TEXTS };
    (Object.keys(DEFAULT_TEXTS) as TextKey[]).forEach(key => {
        const value = source[textPropertyKey(key)]?.value;
        if (value) {
            texts[key] = value;
        }
    });
    return texts;
}
